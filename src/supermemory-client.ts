// Supermemory Client for Local Instance
import fs from 'node:fs';
import path from 'node:path';
import { currentConfig, DEFAULTS } from './config.ts';

export type Result<T> = { success: true; data: T } | { success: false; error: string };

export interface DocumentSummary {
	id: string;
	createdAt: string;
	metadata?: Record<string, unknown> | null;
}

export interface Document extends DocumentSummary {
	content: string | null;
}

export interface SearchResult {
	documentId: string;
	createdAt?: string;
	chunks?: { content: string }[];
}

/** /v4/search result: an extracted memory (`memory`) or, in hybrid mode, a raw document chunk (`chunk`) */
export interface SearchHit {
	id: string;
	memory?: string;
	chunk?: string;
	similarity: number;
	metadata?: Record<string, unknown> | null;
	documents?: { id: string }[];
}

export class SupermemoryClient {
	baseUrl: string;
	apiKey: string;

	constructor(options: { baseUrl?: string; apiKey?: string } = {}) {
		const cfg = currentConfig();
		this.baseUrl = options.baseUrl || cfg.smUrl;
		let key = options.apiKey || cfg.smApiKey;

		// If key is dummy or unset, use the real key generated by the server in data/
		if (!key || key === DEFAULTS.SUPERMEMORY_API_KEY) {
			try {
				key = fs.readFileSync(path.join(cfg.dataDir, 'current', 'api-key'), 'utf-8').trim();
			} catch {
				key = '';
			}
		}

		this.apiKey = key;
	}

	getHeaders(): Record<string, string> {
		const headers: Record<string, string> = {
			'Content-Type': 'application/json',
		};
		if (this.apiKey) headers.Authorization = `Bearer ${this.apiKey}`;
		return headers;
	}

	async isHealthy(): Promise<boolean> {
		try {
			const res = await fetch(`${this.baseUrl}/v3/search/spaces`, {
				headers: this.getHeaders(),
				signal: AbortSignal.timeout(3000),
			});
			return res.status === 200;
		} catch {
			return false;
		}
	}

	/**
	 * JSON request that never throws: { success, data } or { success: false, error }
	 */
	async request<T>(method: string, urlPath: string, body?: unknown): Promise<Result<T>> {
		try {
			const res = await fetch(`${this.baseUrl}${urlPath}`, {
				method,
				headers: this.getHeaders(),
				body: body ? JSON.stringify(body) : undefined,
				signal: AbortSignal.timeout(5000),
			});
			if (!res.ok) {
				return { success: false, error: `HTTP ${res.status}: ${await res.text()}` };
			}
			// DELETE /v3/documents/:id answers 204 with no body
			const text = await res.text();
			return { success: true, data: (text ? JSON.parse(text) : undefined) as T };
		} catch (err) {
			return { success: false, error: (err as Error).message };
		}
	}

	/**
	 * Add a document / memory entry into Supermemory
	 */
	addDocument({
		content,
		containerTags = [],
		metadata = {},
	}: {
		content: string;
		containerTags?: string[];
		metadata?: Record<string, unknown>;
	}) {
		return this.request<{ id: string; status: string }>('POST', '/v3/documents', {
			content,
			containerTags,
			metadata: { ...metadata, timestamp: new Date().toISOString() },
		});
	}

	/**
	 * Newest-first document list (metadata only, no content). Includes documents still
	 * being processed, so a memory written by another agent seconds ago is already visible.
	 */
	async listDocuments({
		containerTags = [],
		limit = 50,
	}: {
		containerTags?: string[];
		limit?: number;
	}): Promise<DocumentSummary[]> {
		const res = await this.request<{ memories?: DocumentSummary[] }>('POST', '/v3/documents/list', {
			containerTags,
			limit,
			sort: 'createdAt',
			order: 'desc',
		});
		return res.success ? res.data.memories || [] : [];
	}

	async getDocument(id: string): Promise<Document | null> {
		const res = await this.request<Document>('GET', `/v3/documents/${encodeURIComponent(id)}`);
		return res.success ? res.data : null;
	}

	/**
	 * Memory search (/v4/search). `hybrid` also returns raw document chunks, which covers documents
	 * whose memory extraction (minutes via 9router) hasn't finished yet
	 */
	async search({
		q,
		containerTags,
		searchMode = 'hybrid',
		limit = 6,
	}: {
		q: string;
		containerTags: string[];
		searchMode?: 'memories' | 'hybrid';
		limit?: number;
	}): Promise<SearchHit[]> {
		// /v4/search is single-space (two tags answer 400): one call per tag, best hits first
		const results = await Promise.all(
			containerTags.map((containerTag) =>
				this.request<{ results?: SearchHit[] }>('POST', '/v4/search', { q, containerTag, searchMode, limit }),
			),
		);
		const hits = results.flatMap((res) => (res.success ? res.data.results || [] : []));
		return containerTags.length > 1 ? hits.sort((a, b) => b.similarity - a.similarity).slice(0, limit) : hits;
	}

	/**
	 * Facts the server extracted for a container tag: `static` (long-lived) and `dynamic` (newest first)
	 */
	async profile(containerTags: string[]): Promise<{ static: string[]; dynamic: string[] } | null> {
		const results = await Promise.all(
			containerTags.map((containerTag) =>
				this.request<{ profile?: { static: string[]; dynamic: string[] } }>('POST', '/v4/profile', { containerTag }),
			),
		);
		const profiles = results.flatMap((res) => (res.success && res.data.profile ? [res.data.profile] : []));
		if (!profiles.length) return null;
		const merge = (pick: (p: { static: string[]; dynamic: string[] }) => string[] | undefined) => [
			...new Set(profiles.flatMap((p) => pick(p) ?? [])),
		];
		return { static: merge((p) => p.static), dynamic: merge((p) => p.dynamic) };
	}

	/**
	 * Search project memories using /v3/search (vector search over chunks)
	 */
	async searchMemories({
		q,
		containerTags = [],
		limit = 10,
		chunkThreshold = 0.05,
	}: {
		q: string;
		containerTags?: string[];
		limit?: number;
		chunkThreshold?: number;
	}): Promise<{ results: SearchResult[]; error?: string }> {
		const res = await this.request<{ results?: SearchResult[] }>('POST', '/v3/search', {
			q,
			limit,
			chunkThreshold,
			containerTags,
		});
		return res.success ? { results: res.data.results || [] } : { results: [], error: res.error };
	}
}
